from typing import (
    Sized,
    AsyncIterator,
    Literal,
    TypeVar,
    ParamSpec,
    Callable,
    Coroutine,
    Awaitable,
    overload,
    cast,
    Any
)
from uuid import (
    UUID,
    NAMESPACE_OID, 
    uuid4,
    uuid5
)
import time
import asyncio
import logging
from concurrent.futures import ThreadPoolExecutor, ProcessPoolExecutor

import lulalib.storage
import lulalib.observers
import lulalib.models
import lulalib.core
import lulalib.enums
import lulalib.exc
from lulalib.scheduler.executor import T_FUT_C_T, executor

P = ParamSpec("P")
RT = TypeVar("RT")
VTT = TypeVar("VTT")


class Scheduler():

    __slots__ = ( "_ob", "backend_proc", "backend_thread",)

    def __init__(self,
                 observer: lulalib.observers.TaskResultObserver,
        ):
        self._ob = observer
        self.backend_thread = ThreadPoolExecutor()
        self.backend_proc = ProcessPoolExecutor()


    def __call__(self,
                 *,
                 type_name: int | bytes | str = 0,
                 name: str | None = None,
                 ttl: int = 0,
                 callbacks: list[T_FUT_C_T] = list(),
                 raise_on_done: bool = False,
                 create_sig_key: bool = True,
                 use_request_id_ctx: bool = True,
                 sig: str | None = None,
                 backend: Literal["proc", "thread"] = "thread",
                 ):
        """
        Straightforward task scheduler that support multiple backends:
        Thread pool,
        Process pool,
        asyncio.

        - kwargs:
            - `expire_sec`: Seconds after the cached result expires; 
            - `callbacks`: Optional callbacks to set to the thread future;
            - `raise_on_done`: Optionally raise `TaskAlreadyDone` exception. This option is useful for rate limiting;
            - `create_sig_key`: Create a key based on the function call signature;
            - `use_request_id_ctx`: Use request ID generated by the server middleware;
            - `backend`: Specify either `proc` or `thread` execution backend to use. This option is ignored when the function is async;

        - raises:
            - `TaskAlreadyDoneError`: Recent result is currently stored and `raise_on_done` is True;
            - `TaskDismissedError`: The task has been and dropped and has never been created;
        
        - returns:
            `TaskResult[T]`: awaitable result wrapper object
        """

        @overload
        def param(
            fn: Callable[P, Coroutine[Any, Any, RT]]
        ) -> Callable[P, Awaitable[lulalib.models.TaskResult[RT]]]:
            ...

        @overload
        def param(
            fn: Callable[P, RT]
        ) -> Callable[P, Awaitable[lulalib.models.TaskResult[RT]]]:
            ...

        def param(
                fn: (
                    Callable[P, RT] |
                    Callable[P, Coroutine[Any, Any, RT]])
            ) -> (
                Callable[P, Awaitable[lulalib.models.TaskResult[RT]]]
            ):
            async def inner(*args: P.args, **kwargs: P.kwargs):
                nonlocal ttl, name
                loop = asyncio.get_event_loop()
                name = name or fn.__name__
                if use_request_id_ctx:
                    operation_id = self._ob.conf.ctx_oid.get()
                else:
                    operation_id = NAMESPACE_OID
                if create_sig_key:
                    call_sig = sig or (f"{fn.__name__}_{args}")
                    key = uuid5(operation_id, call_sig)
                else:
                    key = uuid5(operation_id, name)
                t_result = None
                has_result = await self._ob.storage.contains(key.bytes)
                if self._ob.conf.shutdown.is_set():
                    #await self.task_queue.join()
                    raise lulalib.exc.TaskDismissedError(task_id=key, reason="shutdown")

                if not has_result:
                    logging.debug("[TASK %s] Executing for the first time")
                    if not asyncio.iscoroutinefunction(fn):
                        if backend == "thread":
                            used_backend = self.backend_thread
                        elif backend == "proc":
                            used_backend = self.backend_proc
                        else: 
                            raise ValueError("Unsupported backend name. Either 'thread' or 'proc' is available.")
                        fut = executor(
                            fn, args, kwargs,
                            callbacks,
                            used_backend
                        )
                    else:
                        fut = cast(
                            asyncio.Task[RT],
                            loop.create_task(
                            fn(*args, **kwargs),
                            name=f"task_{key}")
                        )
                    t_result = self._ob.get_task_result(
                        key, time.time() + ttl,
                        self._ob.conf.get_typ_key(type_name)
                    )
                    self._ob.set_callback(fut, t_result)
                    #await self.task_queue.put(t_result)
                    if ttl:
                        await self._ob.storage.set(key, t_result)
                
                if ttl:
                    result = cast(
                        lulalib.models.TaskResult[RT],
                        await self._ob.storage.get(key, strict=True, raise_on_done=True)
                    )
                    if has_result and raise_on_done and result.state in (
                        lulalib.enums.TaskResultState.DONE,
                        lulalib.enums.TaskResultState.ERROR,
                        lulalib.enums.TaskResultState.CANCELLED
                    ):
                        logging.debug("[TASK %s] Got the cached result, but 'raise_on_done' is set", key)
                        raise lulalib.exc.TaskAlreadyDoneError(result=result, task_id=key)
                    else:
                        logging.debug("[TASK %s] Successfully got the cached result")
                        return result
                    
                logging.debug("[TASK %s] Not cached, waiting for executor's result...")
                if t_result:
                    return t_result
                else:
                    raise RuntimeError("No task result retrieved")
            return inner # type: ignore
        return param

